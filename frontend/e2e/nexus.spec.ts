import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function signIn(page: Page) {
  await page.goto('/')
  await page.getByLabel('Username').fill('admin')
  await page.getByLabel('Password').fill('browser-test-only-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: /^Live$/ })).toBeVisible()
}

test('loads dashboard live, changes ranges, browses monitors, and signs out', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await signIn(page)
  await expect(page.getByRole('heading', { name: 'Host details' })).toBeVisible()
  await page.getByRole('button', { name: '7 days' }).click()
  await expect(page.getByRole('button', { name: '7 days' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'Processes' }).click()
  const processRow = page.getByRole('table').locator('tbody tr').first()
  await expect(processRow).toBeVisible()
  await page.getByRole('button', { name: 'Memory' }).click()
  await expect(page.getByRole('columnheader', { name: 'Memory' })).toHaveAttribute('aria-sort', 'descending')
  await page.getByRole('textbox', { name: 'Search processes' }).fill('nexus-no-match-928ft')
  await expect(page.getByText('No matching processes')).toBeVisible()
  await page.getByRole('link', { name: 'Services' }).click()
  await expect(page.getByRole('heading', { name: 'Services', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Containers' }).click()
  await expect(page.getByText('Docker monitoring is off')).toBeVisible()
  await page.getByRole('button', { name: 'Sign out admin' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(pageErrors).toEqual([])
})

test('uses the 360 px file editor, tabs, revisions, and deletion confirmation', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await signIn(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
  await page.getByRole('link', { name: 'Files' }).click()
  await page.getByRole('button', { name: 'New file' }).click()
  await page.getByRole('textbox', { name: 'File name' }).fill('mobile-note.txt')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByText('Created mobile-note.txt')).toBeVisible()
  await page.getByRole('button', { name: 'mobile-note.txt', exact: true }).click()
  const code = page.getByRole('textbox', { name: 'Edit mobile-note.txt' })
  await expect(code).toBeVisible()
  await code.pressSequentially('first revision')
  await expect(page.getByText('Unsaved changes', { exact: true })).toBeVisible()
  await code.press('Control+s')
  await expect(page.getByText('Saved mobile-note.txt')).toBeVisible()
  await code.press('End')
  await code.pressSequentially(' changed')
  await page.getByRole('button', { name: 'Save file' }).click()
  await expect(page.getByText('Saved mobile-note.txt')).toBeVisible()
  await page.getByRole('button', { name: 'Fullscreen', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Exit fullscreen' })).toBeVisible()
  await page.getByRole('button', { name: 'Exit fullscreen' }).click()
  await page.getByRole('button', { name: 'Back to files' }).click()
  await page.getByRole('button', { name: 'README.md', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Edit README.md' })).toBeVisible()
  await page.getByRole('group', { name: 'Open files' }).getByRole('button', { name: 'mobile-note.txt', exact: true }).click()
  await expect(code).toHaveText('first revision changed')
  await page.getByRole('button', { name: 'File revisions' }).click()
  const history = page.locator('.detail-panel')
  await expect(history.getByRole('button', { name: 'Restore', exact: true })).toHaveCount(2)
  await history.getByRole('button', { name: 'Restore', exact: true }).first().click()
  await page.getByRole('button', { name: 'Restore revision', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Restored mobile-note.txt' })).toBeVisible()
  await page.getByRole('button', { name: 'Open tabs (2)' }).click()
  await expect(code).toHaveText('first revision')
  await page.getByRole('button', { name: 'Back to files' }).click()
  await page.getByRole('button', { name: 'Actions for mobile-note.txt' }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  const confirm = page.getByRole('alertdialog')
  await expect(confirm).toBeVisible()
  await confirm.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('button', { name: 'mobile-note.txt', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await confirm.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('Deleted mobile-note.txt')).toBeVisible()
})

test('a concurrent file update preserves the local draft until the administrator reloads', async ({ page }) => {
  await signIn(page)
  await page.getByRole('link', { name: 'Files' }).click()
  await page.getByRole('button', { name: 'README.md', exact: true }).click()
  const code = page.getByRole('textbox', { name: 'Edit README.md' })
  await code.press('Control+Home')
  await code.pressSequentially('local draft ')

  const session = await (await page.request.get('/api/auth/session')).json()
  const source = await (await page.request.get('/api/files/project/file?path=README.md')).json()
  const updated = await page.request.put('/api/files/project/file', {
    headers: { Origin: 'https://127.0.0.1:8875', 'X-CSRF-Token': session.csrf },
    data: { path: 'README.md', content: '# Updated elsewhere\n', expected: source.digest },
  })
  expect(updated.ok()).toBeTruthy()

  await page.getByRole('button', { name: 'Save file' }).click()
  await expect(page.getByRole('alert')).toContainText('The file changed on disk')
  await expect(code).toContainText('local draft')
  await page.getByRole('button', { name: 'Reload from disk' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Discard and reload' }).click()
  await expect(code).toContainText('Updated elsewhere')
})
